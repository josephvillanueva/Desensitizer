using System;
using System.Linq;
using System.Xml.Linq;

namespace Desensitizer
{
 // The pipeline lives in Shared/DocumentProcessorCore.cs. This file holds the
 // two points where the apps differ.
 public static partial class DocumentProcessor
 {
  private static void StripVolatileMetadata(XDocument doc)
  {
   // Word revision-session IDs are editing metadata, not document content.
   // Remove them so an unrelated numeric replacement cannot be mistaken for
   // an unredacted value in an rsid attribute or the settings rsid list.
   foreach(var node in doc.Descendants().Where(x=>x.Name.LocalName is "rsids" or "rsid").ToList())node.Remove();
   foreach(var attribute in doc.Descendants().Attributes().Where(x=>x.Name.LocalName.StartsWith("rsid",StringComparison.OrdinalIgnoreCase)).ToList())attribute.Remove();
   foreach(var attribute in doc.Descendants().Attributes().Where(x=>x.Name.LocalName is "tplc" or "durableId").ToList())attribute.Remove();
  }
  // Attributes the export audit searches for mapped values.
  private static bool IsAuditedAttribute(string partName,XAttribute attribute)=>!IsLayoutAttribute(attribute)&&!IsStandardRelationshipMetadata(partName,attribute)&&!IsStandardFieldMarker(attribute);
  private static bool IsLayoutAttribute(XAttribute attribute)
  {
   XNamespace word="http://schemas.openxmlformats.org/wordprocessingml/2006/main";
   if(attribute.Name==word+"start"&&attribute.Parent?.Name==word+"pgNumType")return true;
   return attribute.Parent?.Name.LocalName=="ind"&&(attribute.Name.LocalName is "left" or "right" or "firstLine" or "hanging");
  }
  private static bool IsStandardRelationshipMetadata(string partName,XAttribute attribute)
  {
   if(!partName.EndsWith(".rels",StringComparison.OrdinalIgnoreCase))return false;
   // These values are generated by Word itself, not copied from the document.
   // Keep all nonstandard targets, including local file paths, under audit.
   if(attribute.Name.LocalName=="Type")return attribute.Value.Equals("http://schemas.openxmlformats.org/officeDocument/2006/relationships/endnotes",StringComparison.Ordinal);
   return attribute.Name.LocalName=="Target"&&attribute.Value.Equals("endnotes.xml",StringComparison.OrdinalIgnoreCase);
  }
  private static bool IsStandardFieldMarker(XAttribute attribute)
  {
   return attribute.Name.LocalName=="fldCharType"&&attribute.Parent?.Name.LocalName=="fldChar"
    &&(attribute.Value=="begin"||attribute.Value=="separate"||attribute.Value=="end");
  }
 }
}
